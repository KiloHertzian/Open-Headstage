// src/sofa/loader.rs

use std::ffi::{CString, NulError};

// This will include the bindings generated by `bindgen` from `build.rs`
#[allow(warnings)]
mod bindings {
    include!(concat!(env!("OUT_DIR"), "/mysofa_bindings.rs"));
}

// Define MYSOFA_OK manually if not correctly picked up by bindgen
const MYSOFA_OK: ::std::os::raw::c_int = 0; // Explicitly use c_int type from std

/// Represents errors that can occur during SOFA file processing.
#[derive(Debug)]
#[allow(dead_code)]
pub enum SofaError {
    /// An error occurred when creating a C-style string.
    Nul(NulError),
    /// An error occurred while opening the SOFA file.
    FileOpen(String),
    /// A generic error reported by the `libmysofa` library.
    Mysofa(String),
    /// An error occurred while retrieving a filter from the SOFA file.
    MysofaFilter(String),
}

impl From<NulError> for SofaError {
    fn from(err: NulError) -> Self {
        SofaError::Nul(err)
    }
}

/// A safe wrapper around the `*mut bindings::MYSOFA_EASY` handle from `libmysofa`.
///
/// This struct manages the lifecycle of the SOFA file handle, ensuring that it is properly
/// closed when the struct goes out of scope. It provides methods to open SOFA files,
/// retrieve Head-Related Transfer Function (HRTF) impulse responses (IRs), and perform
/// coordinate conversions.
#[allow(dead_code)]
pub struct MySofa {
    /// The raw pointer to the `MYSOFA_EASY` struct.
    handle: *mut bindings::MYSOFA_EASY,
    /// The length of the HRIR filters after resampling by `mysofa_open`.
    pub filter_length: usize,
    /// The original sample rate of the SOFA file before any resampling.
    pub source_samplerate: f32,
    /// The sample rate of the HRIRs after resampling by `mysofa_open`.
    pub resampled_samplerate: f32,
}

// libmysofa is not thread-safe for concurrent operations on the same handle.
// However, marking it as `Send` is considered safe if a `MySofa` instance is owned
// by a single thread-safe structure (like the plugin's main struct) and access is
// properly synchronized, which is typical in a VST plugin architecture.
unsafe impl Send for MySofa {}

impl Drop for MySofa {
    /// Closes the SOFA file handle automatically when `MySofa` is dropped.
    fn drop(&mut self) {
        if !self.handle.is_null() {
            unsafe {
                bindings::mysofa_close(self.handle);
            }
            self.handle = std::ptr::null_mut();
        }
    }
}

#[allow(dead_code)]
impl MySofa {
    /// Opens a SOFA file and prepares it for HRIR retrieval.
    ///
    /// The `mysofa_open` function from `libmysofa` handles resampling of the HRIR data
    /// to the specified `target_samplerate`.
    ///
    /// # Arguments
    ///
    /// * `filepath` - The path to the SOFA file.
    /// * `target_samplerate` - The target sample rate to which the HRIRs should be resampled.
    ///
    /// # Returns
    ///
    /// A `Result` containing a new `MySofa` instance on success, or a `SofaError` on failure.
    pub fn open(filepath: &str, target_samplerate: f32) -> Result<Self, SofaError> {
        let c_filepath = CString::new(filepath)?;

        let mut err_code_open = MYSOFA_OK;
        let handle = unsafe {
            bindings::mysofa_open(
                c_filepath.as_ptr(),
                target_samplerate,
                &mut 0, // filter_length is an output parameter, but we read it later.
                &mut err_code_open,
            )
        };

        if err_code_open != MYSOFA_OK || handle.is_null() {
            return Err(SofaError::FileOpen(format!(
                "Failed to open SOFA file '{}'. Mysofa error code: {}",
                filepath, err_code_open
            )));
        }

        let filter_length = unsafe { (*(*handle).hrtf).N } as usize;
        let source_samplerate = unsafe {
            let data_sampling_rate_array = (*(*handle).hrtf).DataSamplingRate;
            if data_sampling_rate_array.values.is_null() {
                return Err(SofaError::Mysofa(
                    "DataSamplingRate values pointer is null.".to_string(),
                ));
            }
            data_sampling_rate_array.values.read()
        };

        Ok(Self {
            handle,
            filter_length,
            source_samplerate,
            resampled_samplerate: target_samplerate,
        })
    }

    /// Retrieves the HRIR pair for a given source position.
    ///
    /// The source position is specified in spherical coordinates (azimuth, elevation, radius)
    /// and is converted to Cartesian coordinates as required by `libmysofa`.
    ///
    /// # Arguments
    ///
    /// * `azimuth_deg` - The azimuth angle in degrees (0° front, positive to the left).
    /// * `elevation_deg` - The elevation angle in degrees (0° horizontal, positive upwards).
    /// * `radius_m` - The distance from the origin in meters.
    ///
    /// # Returns
    ///
    /// A `Result` containing a tuple with the left and right HRIRs as `Vec<f32>`,
    /// or a `SofaError` on failure.
    pub fn get_hrtf_irs(
        &self,
        azimuth_deg: f32,
        elevation_deg: f32,
        radius_m: f32,
    ) -> Result<(Vec<f32>, Vec<f32>), SofaError> {
        if self.handle.is_null() {
            return Err(SofaError::Mysofa(
                "MySofa handle is not initialized.".to_string(),
            ));
        }
        if self.filter_length == 0 {
            return Err(SofaError::Mysofa("Filter length is zero.".to_string()));
        }

        // Convert spherical coordinates to Cartesian for libmysofa.
        let mut cartesian_coords = [
            azimuth_deg.to_radians(),
            elevation_deg.to_radians(),
            radius_m,
        ];
        unsafe {
            bindings::mysofa_s2c(&mut cartesian_coords[0] as *mut f32);
        }

        let mut left_ir_buffer = vec![0.0f32; self.filter_length];
        let mut right_ir_buffer = vec![0.0f32; self.filter_length];
        let mut delay_left_s = 0.0f32;
        let mut delay_right_s = 0.0f32;

        let err_code_filter = unsafe {
            bindings::mysofa_getfilter_float(
                self.handle,
                cartesian_coords[0], // x
                cartesian_coords[1], // y
                cartesian_coords[2], // z
                left_ir_buffer.as_mut_ptr(),
                right_ir_buffer.as_mut_ptr(),
                &mut delay_left_s,
                &mut delay_right_s,
            )
        };

        if err_code_filter != MYSOFA_OK {
            return Err(SofaError::MysofaFilter(format!(
                "mysofa_getfilter_float failed with code: {}",
                err_code_filter
            )));
        }

        Ok((left_ir_buffer, right_ir_buffer))
    }

    /// Converts spherical coordinates to Cartesian coordinates.
    ///
    /// # Arguments
    ///
    /// * `spherical` - A slice `[azimuth_deg, elevation_deg, radius_m]`.
    ///
    /// # Returns
    ///
    /// An array `[x, y, z]` following the AES69 convention (Y up, Z front, X left).
    pub fn spherical_to_cartesian(spherical: &[f32; 3]) -> [f32; 3] {
        let mut cartesian = [
            spherical[0].to_radians(), // azimuth to radians
            spherical[1].to_radians(), // elevation to radians
            spherical[2],              // radius
        ];
        unsafe {
            bindings::mysofa_s2c(&mut cartesian[0] as *mut f32);
        }
        cartesian
    }

    /// Converts Cartesian coordinates to spherical coordinates.
    ///
    /// # Arguments
    ///
    /// * `cartesian` - An array `[x, y, z]` following the AES69 convention.
    ///
    /// # Returns
    ///
    /// An array `[azimuth_deg, elevation_deg, radius_m]`.
    pub fn cartesian_to_spherical(cartesian: &[f32; 3]) -> [f32; 3] {
        let mut spherical = *cartesian;
        unsafe {
            bindings::mysofa_c2s(&mut spherical[0] as *mut f32);
        }
        // spherical is now [azimuth_rad, elevation_rad, radius_m]
        [
            spherical[0].to_degrees(), // azimuth to degrees
            spherical[1].to_degrees(), // elevation to degrees
            spherical[2],              // radius
        ]
    }
}

// Basic tests (more comprehensive tests would require a SOFA file and proper mocking or integration)
#[cfg(test)]
mod tests {
    use super::*;
    use std::path::Path;

    // A dummy SOFA file path for testing.
    // In a real test environment, this should point to an actual minimal SOFA file.
    // For CI, we might need to conditionally skip this test or provide a file.
    const TEST_SOFA_PATH: &str = "assets/test.sofa"; // Placeholder

    #[test]
    fn test_open_non_existent_file() {
        // Use a more specific non-existent path for this test
        match MySofa::open(
            "/tmp/some_hopefully_non_existent_sofa_file_for_test.sofa",
            48000.0,
        ) {
            Err(SofaError::FileOpen(_)) => {
                // Expected error
            }
            Ok(_) => panic!("Should not succeed in opening a non-existent file."),
            Err(e) => panic!("Unexpected error type: {:?}", e),
        }
    }

    #[test]
    fn test_get_hrtf_irs_error_handling() {
        // This test attempts to trigger an error in mysofa_getfilter_float.
        // It requires a valid SOFA file to open successfully first.
        // If TEST_SOFA_PATH doesn't exist, this test will likely fail at the open() call,
        // which is acceptable as we can't easily add test files in this environment.
        // The main purpose is to check the error handling logic if get_hrtf_irs is reached.

        // Check if the placeholder SOFA file exists. If not, we can't proceed to test get_hrtf_irs error.
        // In a real CI, we'd download or ensure this file exists. Here, we'll just print a notice.
        if !Path::new(TEST_SOFA_PATH).exists() {
            eprintln!(
                "Test SOFA file '{}' not found. Skipping HRTF filter error test logic. \
                 This test primarily validates the error path if mysofa_getfilter_float fails.",
                TEST_SOFA_PATH
            );
            // We can still proceed with a dummy MySofa if open fails in a specific way,
            // but the MySofa::open itself will likely fail with FileOpen first.
            // Let's try to open and if it fails, that's the test outcome for now.
        }

        match MySofa::open(TEST_SOFA_PATH, 48000.0) {
            Ok(mysofa) => {
                // Try to get HRIRs with parameters that might be invalid (e.g., radius 0)
                // libmysofa documentation suggests that positions exactly at (0,0,0)
                // or outside the measured range can lead to errors from mysofa_getfilter_float.
                let result = mysofa.get_hrtf_irs(0.0, 0.0, 0.0); // Azimuth, Elevation, Radius (0)

                match result {
                    Err(SofaError::MysofaFilter(_)) => {
                        // This is the expected error type if mysofa_getfilter_float fails.
                        // The error message content (error code) might vary.
                        println!("Successfully caught MysofaFilter as expected.");
                    }
                    Ok(_) => {
                        panic!(
                            "mysofa_getfilter_float did not return an error for potentially invalid parameters (radius 0.0). This might indicate the specific SOFA file handles this case gracefully, or the error condition wasn't triggered as expected."
                        );
                    }
                    Err(e) => {
                        panic!("Expected MysofaFilter, but got a different error: {:?}", e);
                    }
                }
            }
            Err(SofaError::FileOpen(_)) => {
                // This is an expected outcome if the TEST_SOFA_PATH file doesn't exist.
                // The test then implicitly doesn't reach the get_hrtf_irs error check.
                eprintln!(
                    "Could not open test SOFA file '{}'. The test for get_hrtf_irs error handling was not fully executed.",
                    TEST_SOFA_PATH
                );
                // Depending on strictness, this could be a panic or just an accepted state.
                // For now, we accept it as this environment doesn't guarantee the file.
            }
            Err(e) => {
                panic!(
                    "Failed to open test SOFA file with an unexpected error: {:?}",
                    e
                );
            }
        }
    }

    // A very basic test for coordinate conversion round trip, assuming mysofa C functions are correct.
    // This is more of a sanity check for the wrapper.
    #[test]
    fn test_coordinate_conversion_roundtrip() {
        let spherical_in: [f32; 3] = [30.0, 15.0, 1.5]; // Az=30deg, El=15deg, R=1.5m
        let cartesian = MySofa::spherical_to_cartesian(&spherical_in);
        let spherical_out = MySofa::cartesian_to_spherical(&cartesian);

        const TOLERANCE: f32 = 1e-3; // Radians to/from degrees can have small errors
        assert!(
            (spherical_in[0] - spherical_out[0]).abs() < TOLERANCE,
            "Azimuth mismatch"
        );
        assert!(
            (spherical_in[1] - spherical_out[1]).abs() < TOLERANCE,
            "Elevation mismatch"
        );
        assert!(
            (spherical_in[2] - spherical_out[2]).abs() < TOLERANCE,
            "Radius mismatch"
        );
    }
}
