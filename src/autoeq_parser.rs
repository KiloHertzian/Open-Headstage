//! # AutoEQ Profile Parser
//!
//! This module provides functionality to parse headphone equalization profiles
//! from files generated by the [AutoEQ project](https://github.com/jaakkopasanen/AutoEq).
//!
//! The primary function `parse_autoeq_file` reads a text file containing preamp
//! and filter settings and converts them into an `AutoEqProfile` struct, which
//! can then be applied to the parametric equalizer.

use nih_plug::prelude::nih_log;
use std::error::Error;
use std::fs;
use std::path::Path;
use std::str::FromStr;

use crate::dsp::parametric_eq::FilterType;

/// Represents the settings for a single parametric EQ band from an AutoEQ profile.
#[derive(Debug, Clone, PartialEq, serde::Serialize, serde::Deserialize, Default)]
pub struct BandSetting {
    /// Whether the filter band is enabled.
    pub enabled: bool,
    /// The type of the filter (e.g., Peak, LowShelf).
    pub filter_type: FilterType,
    /// The center frequency of the filter in Hz.
    pub frequency: f32,
    /// The Q factor of the filter.
    pub q: f32,
    /// The gain of the filter in dB.
    pub gain: f32,
}

/// Represents a complete AutoEQ profile, including preamp gain and a list of EQ bands.
#[derive(Debug, Clone, Default)]
pub struct AutoEqProfile {
    /// The preamp gain in dB required by the profile.
    pub preamp: f32,
    /// A vector of `BandSetting` structs, one for each filter in the profile.
    pub bands: Vec<BandSetting>,
}

/// Parses a single "Filter" line from an AutoEQ file.
///
/// # Arguments
///
/// * `line` - A string slice representing a single line from the file.
///
/// # Returns
///
/// A `Result` containing a `BandSetting` on success, or a `Box<dyn Error>` on failure.
fn parse_filter_line(line: &str) -> Result<BandSetting, Box<dyn Error>> {
    let parts: Vec<&str> = line.split_whitespace().collect();
    // Example format: "Filter 1: ON PK Fc 8983 Hz Gain 4.4 dB Q 2.63"
    if parts.len() < 12 || parts[0] != "Filter" || parts[2] != "ON" {
        return Err("Invalid filter line format".into());
    }

    let filter_type_str = parts[3];
    let fc_str = parts[5];
    let gain_str = parts[8];
    let q_str = parts[11];

    let filter_type = match filter_type_str {
        "PK" => FilterType::Peak,
        "LSC" => FilterType::LowShelf,
        "HSC" => FilterType::HighShelf,
        _ => return Err(format!("Unknown filter type: {}", filter_type_str).into()),
    };

    Ok(BandSetting {
        enabled: true,
        filter_type,
        frequency: f32::from_str(fc_str)?,
        q: f32::from_str(q_str)?,
        gain: f32::from_str(gain_str)?,
    })
}

/// Parses an AutoEQ profile file.
///
/// Reads the specified file, parsing the preamp value and all filter definitions.
/// Lines that cannot be parsed are skipped.
///
/// # Arguments
///
/// * `path` - A `Path` to the AutoEQ file.
///
/// # Returns
///
/// A `Result` containing a complete `AutoEqProfile` on success, or a `Box<dyn Error>`
/// if the file cannot be read or essential parts cannot be parsed.
pub fn parse_autoeq_file(path: &Path) -> Result<AutoEqProfile, Box<dyn Error>> {
    let content = fs::read_to_string(path)?;
    let mut profile = AutoEqProfile::default();

    for line in content.lines() {
        if line.starts_with("Preamp:") {
            let parts: Vec<&str> = line.split_whitespace().collect();
            if parts.len() >= 2 {
                profile.preamp = f32::from_str(parts[1])?;
            }
        } else if line.starts_with("Filter") {
            match parse_filter_line(line) {
                Ok(band) => profile.bands.push(band),
                Err(e) => nih_log!("Skipping invalid filter line: {}", e),
            }
        }
    }

    Ok(profile)
}
